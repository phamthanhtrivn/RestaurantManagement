   public boolean checkValue() {
    try {
        int soGhe = Integer.parseInt(txtGiamGia.getText().trim());
        int soBan = Integer.parseInt(txtTenKM.getText().trim());

        if (soBan <= 0) {
            JOptionPane.showMessageDialog(null, "Số bàn phải lớn hơn 0!");
            return false;
        }

        if (soGhe <= 0 || soGhe >= 20) {
            JOptionPane.showMessageDialog(null, "Số ghế phải lớn hơn 0 và nhỏ hơn 20!");
            return false;
        }

        return true;
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null, "Vui lòng nhập số nguyên hợp lệ cho số bàn và số ghế!");
        return false;
    }
}

