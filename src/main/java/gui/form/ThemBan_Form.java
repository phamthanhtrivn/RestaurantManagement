    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
    BanDAO banDAO = new BanDAOImpl(Ban.class);
    LoaiBanDAO loaiBanDAO = new LoaiBanDAOImpl(LoaiBan.class);
        List<Ban> list = banDAO.getAll();
    if (checkValue()) {
        
       int soBan= Integer.parseInt(txtTenKM.getText());
       int soGhe = Integer.parseInt(txtGiamGia.getText());
       int tinhTrang = 1;
       LoaiBan loaiBan = loaiBanDAO.getLoaiBanByName((String) cbbtt.getSelectedItem());
       LoaiBan lb= new LoaiBan();
       lb.setMaLB(loaiBan.getMaLB());
       for(Ban b :list){
           if(b.getLoaiBan().getMaLB().equalsIgnoreCase(lb.getMaLB())){
               if(b.getSoBan()==soBan){
                   JOptionPane.showMessageDialog(this, "tầng này đã có số bàn đó vui lòng nhập số bàn khác ");
                   return;
               }
           }
       }

       String ma = banDAO.maTuSinh(lb.getMaLB());
       JOptionPane.showMessageDialog(this, ma);

       Ban emp = new Ban(ma, soBan, soGhe, tinhTrang, lb);
       
       if(banDAO.save(emp)){
           JOptionPane.showMessageDialog(this, "thêm bàn thành công");
                parentPanel.refreshTable();
                this.dispose();
       }
       else{
            JOptionPane.showMessageDialog(this, "Lỗi khi lưu bàn vào cơ sở dữ liệu");

       }
            
          
    }

    }//GEN-LAST:event_jButton1ActionPerformed

