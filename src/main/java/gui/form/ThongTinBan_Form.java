    public void setData(String ma){


        BanDAO banDAO = new  BanDAOImpl(Ban.class);
        Ban ban = banDAO.findById(ma);
        String maBan = ban.getMaBan();
        int soBan= ban.getSoBan();
        int soGhe = ban.getSoGhe();
        int tinhTrang = ban.getTinhTrang();
        String loaiBan = ban.getLoaiBan().getTenLB();
        makm.setText(maBan);
        loai.setText(""+soBan);
        giamgia.setText(""+soGhe);
        ten.setText(loaiBan);
        if(tinhTrang>0){
            radat.setSelected(true);
            
        }
        else{
            rahuy.setSelected(true);
        }
        if(radat.isSelected()){
            rahuy.setSelected(false);
        }
        else{
            rahuy.setSelected(true);

                }
             
              
    }
    
    

