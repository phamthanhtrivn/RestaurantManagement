    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed


            BanDAO banDAO = new BanDAOImpl(Ban.class);
            LoaiBanDAO loaiBanDAO = new LoaiBanDAOImpl(LoaiBan.class);
            String ma = makm.getText().trim();
            int soBan = Integer.parseInt(loai.getText());
            int soGhe;

            try {
                soGhe = Integer.parseInt(giamgia.getText().trim());
                if (soGhe <= 0 || soGhe > 20) {
                    JOptionPane.showMessageDialog(this, "Số ghế phải là số nguyên lớn hơn 0 và nhỏ hơn hoặc bằng 20!");
                    return; // Dừng xử lý nếu không hợp lệ
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập số nguyên hợp lệ cho số ghế!");
                return;
            }
            String tenLB = ten.getText();
            LoaiBan loaiBan = loaiBanDAO.getLoaiBanByName(tenLB);
            int trangThai=0;
            if(radat.isSelected()){
                 trangThai = 1;
            }
            else{
                trangThai=0;
            }
            Ban ban = new Ban(ma, soBan, soGhe, trangThai, loaiBan);
            
            if(banDAO.update(ban)){
                  JOptionPane.showMessageDialog(this, "Cập nhật thành công!");
                 parentPanel.refreshTable();
                 this.dispose();
            }
             else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại.");
        }
                 
        
    }//GEN-LAST:event_jButton1ActionPerformed

